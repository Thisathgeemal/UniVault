// Generates src/fixtures/diagnostics-credential.ts: a SYNTHETIC SD-JWT credential that the
// Diagnostics screen (and a Jest test) decode with @univault/crypto-core to prove the shared
// crypto code runs in the wallet.
//
// - Runs on Node at development time only (`npm run fixture:diagnostics`); it is the only wallet
//   file that may use @univault/crypto-core/node. The app imports the universal entry only.
// - The RS256 issuer key and the EC holder key are generated here and THROWN AWAY: no private
//   key is written anywhere. Only the signed credential (public data) is saved.
// - Every claim is invented test data (no real person); the issuer is an .example domain.
import { generateKeyPairSync } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createSdJwt, decodeSdJwt, generateIssuerKeys } from '@univault/crypto-core/node';

const issuer = await generateIssuerKeys(); // throwaway, in memory only
const { publicKey: holderPublic } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
const { kty, crv, x, y } = holderPublic.export({ format: 'jwk' });

const disclosable = {
  employee_id: 'DIAG-0001',
  full_name: 'Diagnostics Test Holder',
  designation: 'Test Engineer',
  department: 'Quality Assurance',
  employment_type: 'full_time',
};

const sdJwt = await createSdJwt(
  {
    iss: 'https://issuer.example/univault-diagnostics',
    vct: 'urn:univault:vct:EmploymentCredential:1',
    issuer_name: 'UniVault Diagnostics (synthetic)',
    schema_version: '1.0',
    iat: 1798761600, // 1 Jan 2027 00:00 UTC (fixed, so the file is reproducible apart from salts)
    exp: 4102444800, // 1 Jan 2100: the check decodes only, it never checks expiry
    cnf: { jwk: { kty, crv, x, y } },
    ...disclosable,
  },
  Object.keys(disclosable),
  { kid: issuer.kid, privateKey: issuer.privateKeyPem },
);

// Self-check before writing
const decoded = await decodeSdJwt(sdJwt);
if (decoded.disclosures.length !== Object.keys(disclosable).length) {
  throw new Error('fixture self-check failed: wrong number of disclosures');
}

const target = fileURLToPath(new URL('../src/fixtures/diagnostics-credential.ts', import.meta.url));
const source = `/**
 * SYNTHETIC test credential for the Diagnostics "crypto-core check" (and its Jest test).
 * GENERATED by \`npm run fixture:diagnostics\` (scripts/make-diagnostics-fixture.mjs): do not edit.
 *
 * Invented data only. Signed with a throwaway RS256 key that was discarded after signing, so
 * no private key exists anywhere; the signature is not checked (decoding only).
 */
export const DIAGNOSTICS_CREDENTIAL = {
  sdJwt:
    '${sdJwt}',
  /** Claim names that must come back as disclosures, in issuance order. */
  disclosedClaims: [${Object.keys(disclosable)
    .map((name) => `'${name}'`)
    .join(', ')}],
  vct: 'urn:univault:vct:EmploymentCredential:1',
} as const;
`;
writeFileSync(target, source);
console.log(`wrote ${target} (${decoded.disclosures.length} disclosures)`);
